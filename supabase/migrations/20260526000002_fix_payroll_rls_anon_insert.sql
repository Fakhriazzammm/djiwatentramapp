-- =============================================================================
-- Fix: Payroll tables RLS — tambah INSERT/UPDATE/DELETE for anon
-- =============================================================================
-- Masalah: Frontend (payroll period panel) mengirim INSERT/UPDATE via edge
-- function generate-payroll. Tapi ada kasus edge function gagal dipanggil
-- atau Management API token tidak dikonfigurasi, sehingga query jatuh ke
-- Supabase client biasa yang RLS-enabled.
--
-- Fix: Tambah INSERT/UPDATE/DELETE policies untuk anon role pada payroll
-- tables yang perlu write access dari frontend.
-- =============================================================================

-- =============================================================================
-- pos.payroll_periods — CREATE, UPDATE, DELETE
-- =============================================================================
drop policy if exists "payroll_periods_anon_insert" on pos.payroll_periods;
create policy "payroll_periods_anon_insert"
  on pos.payroll_periods for insert to anon, authenticated
  with check (true);

drop policy if exists "payroll_periods_anon_update" on pos.payroll_periods;
create policy "payroll_periods_anon_update"
  on pos.payroll_periods for update to anon, authenticated
  using (true) with check (true);

drop policy if exists "payroll_periods_anon_delete" on pos.payroll_periods;
create policy "payroll_periods_anon_delete"
  on pos.payroll_periods for delete to anon, authenticated
  using (true);

