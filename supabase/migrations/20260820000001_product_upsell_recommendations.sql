-- Database-driven customer upsell recommendations.
-- Additive migration: no existing data is removed or renamed.

create table if not exists pos.product_upsell_recommendations (
  id bigint generated by default as identity primary key,
  product_source_id text not null,
  recommended_product_source_id text not null,
  sort_order integer not null default 0,
  title_override text,
  description_override text,
  cta_label text,
  max_quantity integer,
  requires_options boolean,
  is_active boolean not null default true,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint product_upsell_recommendations_unique_pair
    unique (product_source_id, recommended_product_source_id),
  constraint product_upsell_recommendations_no_self_pair
    check (product_source_id <> recommended_product_source_id),
  constraint product_upsell_recommendations_sort_order_nonnegative
    check (sort_order >= 0),
  constraint product_upsell_recommendations_max_quantity_positive
    check (max_quantity is null or max_quantity > 0)
);

create index if not exists idx_product_upsell_recommendations_source_active
  on pos.product_upsell_recommendations (product_source_id, is_active, sort_order);

alter table pos.product_upsell_recommendations enable row level security;

create or replace view public.pos_product_upsell_recommendations as
select
  r.product_source_id,
  r.recommended_product_source_id,
  r.sort_order,
  r.title_override,
  r.description_override,
  r.cta_label,
  r.max_quantity,
  coalesce(r.requires_options, case when jsonb_typeof(coalesce(recommended.variations, '[]'::jsonb)) = 'array' then jsonb_array_length(recommended.variations) > 0 else false end) as requires_options,
  recommended.name as recommended_name,
  recommended.description as recommended_description,
  recommended.image as recommended_image,
  recommended.price as recommended_price,
  recommended.promo_price as recommended_promo_price,
  recommended.category_source_id as recommended_category_id,
  recommended.variations as recommended_variations
from pos.product_upsell_recommendations r
join pos.products source_product
  on source_product.source_id = r.product_source_id
join pos.products recommended
  on recommended.source_id = r.recommended_product_source_id
where r.is_active = true
  and (r.starts_at is null or r.starts_at <= now())
  and (r.ends_at is null or r.ends_at >= now())
  and source_product.is_available = true
  and recommended.is_available = true
  and (recommended.quantity is null or recommended.quantity > 0)
order by r.product_source_id, r.sort_order, r.id;

grant usage on schema pos to anon, authenticated;
grant select on public.pos_product_upsell_recommendations to anon, authenticated;
grant select on pos.product_upsell_recommendations to service_role;
grant insert, update, delete on pos.product_upsell_recommendations to service_role;
grant usage, select on sequence pos.product_upsell_recommendations_id_seq to service_role;

