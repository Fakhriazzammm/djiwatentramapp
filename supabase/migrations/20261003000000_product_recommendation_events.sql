-- Recommendation analytics: append-only, idempotent events.
create table if not exists pos.product_recommendation_events (
  id bigint generated by default as identity primary key,
  event_key text not null,
  event_type text not null check (event_type in ('impression','click','add_to_cart')),
  product_source_id text,
  recommended_product_source_id text,
  strategy text not null default 'mixed',
  placement text not null default 'inline_menu',
  customer_source_id text,
  session_id text,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  constraint product_recommendation_events_event_key_uniq unique (event_key),
  constraint product_recommendation_events_payload_size check (octet_length(event_key) between 8 and 128 and octet_length(strategy) <= 64 and octet_length(placement) <= 64)
);
create index if not exists product_recommendation_events_pair_idx on pos.product_recommendation_events (recommended_product_source_id, event_type, occurred_at desc);
create index if not exists product_recommendation_events_customer_idx on pos.product_recommendation_events (customer_source_id, occurred_at desc);
revoke all on pos.product_recommendation_events from anon, authenticated;
grant usage on schema pos to anon, authenticated;
create or replace function pos.record_product_recommendation_event(
  p_event_key text,
  p_event_type text,
  p_product_source_id text default null,
  p_recommended_product_source_id text default null,
  p_strategy text default 'mixed',
  p_placement text default 'inline_menu',
  p_customer_source_id text default null,
  p_session_id text default null,
  p_metadata jsonb default '{}'::jsonb
) returns void language plpgsql security definer set search_path = pos, public as $$
begin
  if p_event_key is null or p_event_type not in ('impression','click','add_to_cart') then return; end if;
  insert into pos.product_recommendation_events(event_key,event_type,product_source_id,recommended_product_source_id,strategy,placement,customer_source_id,session_id,metadata)
  values (left(p_event_key,128),p_event_type,left(p_product_source_id,160),left(p_recommended_product_source_id,160),left(coalesce(p_strategy,'mixed'),64),left(coalesce(p_placement,'inline_menu'),64),left(p_customer_source_id,160),left(p_session_id,160),case when jsonb_typeof(coalesce(p_metadata,'{}'::jsonb))='object' then p_metadata else '{}'::jsonb end)
  on conflict (event_key) do nothing;
end; $$;
revoke all on function pos.record_product_recommendation_event(text,text,text,text,text,text,text,text,jsonb) from public;
grant execute on function pos.record_product_recommendation_event(text,text,text,text,text,text,text,text,jsonb) to anon, authenticated;
