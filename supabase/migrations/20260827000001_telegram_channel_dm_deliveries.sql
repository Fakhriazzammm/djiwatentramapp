-- Durable dedupe ledger for channel-to-employee DM relay.
create table if not exists public.telegram_channel_dm_deliveries (
  id bigint generated by default as identity primary key,
  channel_id bigint not null,
  channel_message_id bigint not null,
  telegram_user_id bigint not null,
  employee_name text,
  status text not null default 'pending' check (status in ('pending', 'sent', 'failed', 'blocked')),
  dm_message_id bigint,
  error_message text,
  created_at timestamptz not null default now(),
  sent_at timestamptz,
  unique (channel_id, channel_message_id, telegram_user_id)
);

create index if not exists idx_telegram_channel_dm_deliveries_message
  on public.telegram_channel_dm_deliveries (channel_id, channel_message_id);

alter table public.telegram_channel_dm_deliveries enable row level security;
revoke all on public.telegram_channel_dm_deliveries from anon, authenticated;
grant select, insert, update on public.telegram_channel_dm_deliveries to service_role;
