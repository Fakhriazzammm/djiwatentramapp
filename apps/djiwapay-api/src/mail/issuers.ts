/** Every bank, e-wallet and biller Djiwa Pay can read. One place for both ways money news arrives:
 *  e-mail (the sender's domain, which must also pass DKIM/DMARC) and the Android notification (the sending app's package name).
 *  A wrong or missing entry is harmless: it never matches, so nothing is read from it. */
export type IssuerKind = "bank" | "ewallet" | "service";
export type Issuer = { id: string; name: string; kind: IssuerKind; domains: string[]; /** Android package names of the official app(s). */ packages: string[] };

const bank = (id: string, name: string, domains: string[], packages: string[] = []): Issuer => ({ id, name, kind: "bank", domains, packages });
const wallet = (id: string, name: string, domains: string[], packages: string[] = []): Issuer => ({ id, name, kind: "ewallet", domains, packages });
const biller = (id: string, name: string, domains: string[], packages: string[] = []): Issuer => ({ id, name, kind: "service", domains, packages });

