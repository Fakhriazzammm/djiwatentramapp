#!/usr/bin/env node
/**
 * Fetch PWA settings from Supabase pos_site_settings via REST API and write to app source files.
 * No dependencies — uses fetch() to call Supabase REST API directly.
 *
 * Usage: node scripts/generate-pwa-manifest.mjs
 */

import { writeFileSync } from "fs";
import { resolve, dirname } from "path";
import { fileURLToPath } from "url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const SUPABASE_URL = process.env.VITE_SUPABASE_URL || process.env.SUPABASE_URL;
const SUPABASE_KEY =
	process.env.VITE_SUPABASE_ANON_KEY || process.env.SUPABASE_ANON_KEY;

const DEFAULT_POS = {
	name: "Djiwa Tentram POS",
	short_name: "Djiwa Tentram POS",
	description: "Aplikasi kasir Djiwa Tentram",
	theme_color: "#fefefe",
	background_color: "#0a0a0b",
	start_url: "/menu",
	orientation: "landscape",
	icon192: "/pwa-192x192.png",
	icon512: "/pwa-512x512.png",
};

const DEFAULT_KARYAWAN = {
	name: "Djiwa Tentram Karyawan",
	short_name: "Djiwa Tentram HR",
	description: "Portal karyawan Djiwa Tentram — absensi, jadwal, slip gaji",
	theme_color: "#1a5dc6",
	background_color: "#ffffff",
	start_url: "/",
	orientation: "portrait",
	icon192: "/pwa-192x192.png",
	icon512: "/pwa-512x512.png",
};

const DEFAULT_CUSTOMER = {
	name: "Djiwa Tentram App",
	short_name: "Djiwa Tentram App",
	description: "Pesan menu favorit dari meja",
	theme_color: "#fefefe",
	background_color: "#ffffff",
	start_url: "/djiwatentram",
	orientation: "portrait",
	icon192: "/pwa-app-192.png",
	icon512: "/pwa-app-512.png",
};

async function main() {
		let posPwa = DEFAULT_POS;
		let customerPwa = DEFAULT_CUSTOMER;
		let karyawanPwa = DEFAULT_KARYAWAN;

	if (!SUPABASE_URL || !SUPABASE_KEY) {
		console.warn("⚠ SUPABASE_URL/KEY not set — using defaults");
	} else {
		try {
			const url = `${SUPABASE_URL}/rest/v1/pos_site_settings?select=raw&order=_id.desc&limit=1&raw=not.is.null`;
			const resp = await fetch(url, {
				headers: {
					apikey: SUPABASE_KEY,
					Authorization: `Bearer ${SUPABASE_KEY}`,
				},
			});

			if (!resp.ok) throw new Error(`HTTP ${resp.status}`);

			const rows = await resp.json();
			const raw = rows?.[0]?.raw;

			if (raw?.posPwa) {
				posPwa = { ...DEFAULT_POS, ...raw.posPwa };
			}
			if (raw?.customerPwa) {
				customerPwa = { ...DEFAULT_CUSTOMER, ...raw.customerPwa };
			}
			console.log("✓ PWA settings fetched from Supabase");
		} catch (err) {
			console.warn("⚠ Failed to fetch PWA settings, using defaults:", err.message);
		}
	}

	const posContent = `// Generated by scripts/generate-pwa-manifest.mjs — do not edit manually
// Defaults digunakan saat build script gagal fetch dari Supabase

export const posPwaSettings = ${JSON.stringify(posPwa, null, "\t")};
`;

	const customerContent = `// Generated by scripts/generate-pwa-manifest.mjs — do not edit manually
// Defaults digunakan saat build script gagal fetch dari Supabase

export const customerPwaSettings = ${JSON.stringify(customerPwa, null, "\t")};
`;

		const karyawanContent = `// Generated by scripts/generate-pwa-manifest.mjs — do not edit manually
	// Defaults digunakan saat build script gagal fetch dari Supabase

	export const karyawanPwaSettings = ${JSON.stringify(karyawanPwa, null, "	")};
	`;

		writeFileSync(resolve(ROOT, "apps/pos/src/pwa-settings.ts"), posContent);
		writeFileSync(resolve(ROOT, "apps/customer/src/pwa-settings.ts"), customerContent);
		writeFileSync(resolve(ROOT, "apps/karyawan/src/pwa-settings.ts"), karyawanContent);

		console.log("✓ pwa-settings.ts generated for pos, customer, karyawan");
}

main();
