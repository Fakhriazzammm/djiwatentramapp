#!/bin/bash
# Update version.ts with current git info
# Run this script during build/deploy

cd "$(dirname "$0")/.."

# Get git info
COMMIT_HASH=$(git rev-parse --short HEAD 2>/dev/null || echo "local")
BUILD_DATE=$(date +%Y-%m-%d)

# Get total commit count for auto-incrementing build number
COMMIT_COUNT=$(git rev-list --count HEAD 2>/dev/null || echo "0")

# Read major.minor from package.json, use commit count as patch
BASE_VERSION=$(node -p "require('./package.json').version" 2>/dev/null || echo "0.1.0")
MAJOR=$(echo "$BASE_VERSION" | cut -d. -f1)
MINOR=$(echo "$BASE_VERSION" | cut -d. -f2)

# Auto-generate version: MAJOR.MINOR.COMMIT_COUNT
PACKAGE_VERSION="${MAJOR}.${MINOR}.${COMMIT_COUNT}"

# Create version.ts content
cat > apps/web/src/lib/version.ts << EOF
// Version information - auto-generated by update-version.sh
// Last updated: ${BUILD_DATE}
export const APP_VERSION = {
	// Release version: MAJOR.MINOR.BUILD_NUMBER (build = git commit count)
	semantic: "${PACKAGE_VERSION}",
	// Git commit hash (short)
	commitHash: "${COMMIT_HASH}",
	// Build timestamp
	buildDate: "${BUILD_DATE}",
	// Full version string for display
	getDisplayVersion: () => {
		return \`\${APP_VERSION.semantic}\`;
	},
	// Check if this is a development build
	isDev: import.meta.env.DEV,
} as const;

// Helper to get version info for footer
export function getAppVersionInfo() {
	return {
		version: APP_VERSION.semantic,
		commit: APP_VERSION.commitHash,
		buildDate: APP_VERSION.buildDate,
		fullVersion: APP_VERSION.getDisplayVersion(),
	};
}
EOF

echo "✓ Version updated: ${PACKAGE_VERSION} build:${COMMIT_COUNT} hash:${COMMIT_HASH} (${BUILD_DATE})"
