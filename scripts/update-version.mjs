// Update version.ts with current git/deploy info
// Run this script during build/deploy

import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { getBuildMetadata, incrementBuildCounter } from "./version-metadata.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(__dirname, "..");

// Increment counter SEKALI di awal build
incrementBuildCounter(rootDir);

const metadata = getBuildMetadata(rootDir);

const versionContent = `// Version information - auto-generated by update-version.mjs
// Last updated: ${metadata.buildDate}
export const APP_VERSION = {
	// Release version: MAJOR.MINOR.BUILD_COUNTER
	// Contoh: 0.2.1, 0.2.2 — clean semver, auto-increment tiap build
	semantic: "${metadata.version}",
	// Git/deploy commit hash (short)
	commitHash: "${metadata.commitHash}",
	message: ${JSON.stringify(metadata.commitMessage)},
	// Commit subject for the update prompt
	commitMessage: ${JSON.stringify(metadata.commitMessage)},
	// Build timestamp
	buildDate: "${metadata.buildDate}",
	// Full version string for display
	getDisplayVersion: () => {
		return \`\${APP_VERSION.semantic}\`;
	},
	// Check if this is a development build
	isDev: import.meta.env.DEV,
} as const;

// Helper to get version info for footer
export function getAppVersionInfo() {
	return {
		version: APP_VERSION.semantic,
		commit: APP_VERSION.commitHash,
		message: APP_VERSION.commitMessage,
		buildDate: APP_VERSION.buildDate,
		fullVersion: APP_VERSION.getDisplayVersion(),
	};
}
`;

// A package build runs with that app as cwd. Only update the current app so
// building one app cannot make every other app report a false update.
const allAppDirs = ["apps/admin", "apps/pos", "apps/customer", "apps/karyawan", "apps/ordermieyamin", "apps/booking", "apps/linkbio", "apps/merchandise", "apps/b2b", "apps/kolmarketing"];
const cwdRelative = resolve(process.cwd()).startsWith(`${rootDir}/apps/`) ? resolve(process.cwd()).slice(rootDir.length + 1) : "";
const appDirs = cwdRelative && allAppDirs.includes(cwdRelative) ? [cwdRelative] : allAppDirs;
for (const dir of appDirs) {
	const targetPath = resolve(rootDir, `${dir}/src/lib/version.ts`);
	try {
		writeFileSync(targetPath, versionContent);
	} catch {
		// Directory may not exist (e.g. monorepo sub-app deployed individually on Vercel)
		console.warn(`⚠ Skipping ${dir}/src/lib/version.ts (not available)`);
	}
}

console.log(
	`✓ Version updated: ${metadata.version} build:${metadata.commitCount} hash:${metadata.commitHash} (${metadata.buildDate})`,
);
