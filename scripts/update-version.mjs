// Update version.ts with current git info
// Run this script during build/deploy

import { execSync } from "node:child_process";
import { writeFileSync, readFileSync } from "node:fs";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const rootDir = `${__dirname}/..`;

function runCommand(cmd, fallback) {
	try {
		return execSync(cmd, { cwd: rootDir, encoding: "utf-8" }).trim();
	} catch {
		return fallback;
	}
}

// Get git info
const commitHash = runCommand("git rev-parse --short HEAD", "local");
const buildDate = new Date().toISOString().split("T")[0];
const commitCount = runCommand("git rev-list --count HEAD", "0");

// Read major.minor from package.json
let baseVersion = "0.1.0";
try {
	const pkg = JSON.parse(readFileSync(`${rootDir}/package.json`, "utf-8"));
	baseVersion = pkg.version || baseVersion;
} catch {}

const [major, minor] = baseVersion.split(".");
const packageVersion = `${major}.${minor}.${commitCount}`;

// Create version.ts content
const versionContent = `// Version information - auto-generated by update-version.mjs
// Last updated: ${buildDate}
export const APP_VERSION = {
	// Release version: MAJOR.MINOR.BUILD_NUMBER (build = git commit count)
	semantic: "${packageVersion}",
	// Git commit hash (short)
	commitHash: "${commitHash}",
	// Build timestamp
	buildDate: "${buildDate}",
	// Full version string for display
	getDisplayVersion: () => {
		return \`\${APP_VERSION.semantic}\`;
	},
	// Check if this is a development build
	isDev: import.meta.env.DEV,
} as const;

// Helper to get version info for footer
export function getAppVersionInfo() {
	return {
		version: APP_VERSION.semantic,
		commit: APP_VERSION.commitHash,
		buildDate: APP_VERSION.buildDate,
		fullVersion: APP_VERSION.getDisplayVersion(),
	};
}
`;

writeFileSync(`${rootDir}/apps/web/src/lib/version.ts`, versionContent);

console.log(
	`✓ Version updated: ${packageVersion} build:${commitCount} hash:${commitHash} (${buildDate})`,
);
