// Scopes apps/manager/src/proto.css under .mgr-proto for the Owner page in apps/admin.
// Run: node scripts/gen-manager-proto-css.mjs
import { readFileSync, writeFileSync } from "node:fs";

const css = readFileSync("apps/manager/src/proto.css", "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
const blocks = [];
let depth = 0, start = 0;
for (let i = 0; i < css.length; i++) {
  if (css[i] === "{") depth++;
  else if (css[i] === "}" && --depth === 0) { blocks.push(css.slice(start, i + 1).trim()); start = i + 1; }
}
const head = [], rootProps = [], nested = [];
for (const b of blocks) {
  const sel = b.slice(0, b.indexOf("{")).trim();
  const props = b.slice(b.indexOf("{") + 1, -1);
  if (b.startsWith("@font-face") || b.startsWith("@keyframes")) head.push(b.replace("/fonts/", "/fonts/command-center/"));
  else if (sel === ":root") rootProps.push(props);
  else if (sel === "html,body") continue;
  else if (sel === "body") rootProps.push(props.replace(/overflow:hidden;?/, ""));
  else if (sel === "*") nested.push(`&,& *{${props}}`);
  else nested.push(b);
}
writeFileSync(
  "apps/admin/src/routes/admin/-manager/proto-scoped.css",
  `/* Generated by scripts/gen-manager-proto-css.mjs from apps/manager/src/proto.css. Do not edit by hand. */\n${head.join("\n")}\n.mgr-proto{${rootProps.join(";")};min-height:100%;position:relative;height:auto;overflow:visible}\n.mgr-proto{\n${nested.join("\n")}\n}\n`,
);
console.log("ok");
